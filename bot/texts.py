def progress_bar(day: int, total: int = 30) -> str:
    """Прогресс-бар из символов."""
    filled = int(day / total * 20)
    empty = 20 - filled
    return f"[{'█' * filled}{'░' * empty}] {day}/{total}"


def get_motivation(streak: int) -> str:
    """Мотивационная фраза по стрику."""
    import random
    return random.choice(MOTIVATIONS)
